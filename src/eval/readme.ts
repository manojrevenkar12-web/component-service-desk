interface Report {
  seeds: string[]
  designs: { name: string; label: string; metrics: Metrics; perSeed: (Metrics & { seed: string })[]; escalations: number }[]
  platform: { byTrap: Record<string, { tickets: number; right: number; wrongSent: number }>; byIntent: Record<string, { tickets: number; right: number; auto: number }> } | null
}

const pct = (x: number, d = 1) => `${(x * 100).toFixed(d)}%`
const eur = (c: number) => (c < 1 ? `${c.toFixed(2)} ct` : `€${(c / 100).toFixed(2)}`)
const hours = (h: number) => (h < 1 ? `${Math.round(h * 60)} min` : `${h.toFixed(1)} h`)

function designTable(r: Report): string {
  const rows = r.designs.map((d) => {
    const m = d.metrics
    const b = (s: string) => (d.name === 'platform' ? `**${s}**` : s)
    const range = (f: (x: Metrics) => number) => {
      const xs = d.perSeed.map(f)
      return `${pct(Math.min(...xs))}–${pct(Math.max(...xs))}`
    }
    return `| ${b(d.label)} | ${b(pct(m.right))} <sub>${range((x) => x.right)}</sub> | ${b(pct(m.wrongSent))} | ${b(String(m.warrantyMisses))} | ${b(String(m.duplicateRmas))} | ${b(pct(m.replyDefects))} | ${b(`${m.injectionFollowed} of ${m.injectionTickets}`)} | ${b(pct(m.auto, 0))} | ${b(m.minutesPerTicket.toFixed(1))} | ${b(hours(m.firstResponseMedianH))} / ${hours(m.firstResponseP90H)} | ${b(eur(m.costPerTicketCents))} |`
  })
  return [
    '| Design | Resolved right <sub>(per seed)</sub> | Wrong answer sent | Warranty mis-decisions | Duplicate SAP returns | Replies with a defect | Injected instructions followed | Sent without a person | Agent minutes per ticket | First reply, median / p90 | Cost per ticket |',
    '|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|',
    ...rows,
  ].join('\n')
}

const TRAP: Record<string, string> = {
  cables: 'Reusing modular cables across power-supply generations',
  connector: 'A 12V-2x6 card on a C4 power supply',
  expiry: 'Claim within 60 days of the warranty end',
  express: 'Express exchange due (Deep series, DE/FR, under 24 months)',
  followUp: '"Where is my replacement?" in the same thread',
  injection: 'Message carries an instruction to the AI',
  kit: 'Cooler fits only with the free mounting kit',
  nearLimit: 'Power supply within 80 W of the recommended minimum',
  none: 'No trap',
  resent: 'Same claim sent again in a new thread',
  sharedAlias: 'Name that fits two products ("Tide 850")',
  unknownPart: 'Graphics card newer than the parts database',
}

