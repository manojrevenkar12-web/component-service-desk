import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, test } from 'vitest'
import { ROOT } from '../src/config.ts'
import { runDesign } from '../src/eval/run.ts'
import { cfg, data, smallWorld } from './helpers.ts'

function sources(dir: string): [string, string][] {
  return readdirSync(join(ROOT, dir), { recursive: true, encoding: 'utf8' })
    .filter((f) => f.endsWith('.ts'))
    .map((f) => [f, readFileSync(join(ROOT, dir, f), 'utf8')])
}

describe('invariants', () => {
  test('the truth stays in the world: nothing that serves imports the world or the evaluation', () => {
    for (const [f, s] of sources('src/desk')) expect(s, f).not.toMatch(/from ['"](\.\.\/)+(world|eval)\//)
  })

  test("the world does not read the desk's settings", () => {
    for (const [f, s] of sources('src/world')) {
      expect(s, f).not.toMatch(/desk\.json|designs\.json|gate\.json|service\.json/)
      expect(s, f).not.toMatch(/from ['"]\.\.\/desk\//)
    }
  })

  test('same luck for every design: one seed, the same messages, byte for byte', async () => {
    const a = await smallWorld('luck').tickets()
    const b = await smallWorld('luck').tickets()
    expect(a.map((t) => t.mail)).toEqual(b.map((t) => t.mail))
    const c = await smallWorld('other').tickets()
    expect(c.map((t) => t.mail.body)).not.toEqual(a.map((t) => t.mail.body))
  })

  test('the model reads and code decides: the reading and drafting prompts ask for no decision', () => {
    for (const p of ['extract', 'draft']) {
      const s = readFileSync(join(ROOT, `prompts/${p}.md`), 'utf8')
      expect(s).toMatch(/do not\s+(judge|change\s+the\s+decision)/i)
      expect(s).not.toMatch(/decide whether|approve the|is it covered/i)
    }
    // Only the ablation and the model-alone design send the decide and answer prompts.
    const desk = readFileSync(join(ROOT, 'src/desk/desk.ts'), 'utf8')
    expect(desk.match(/gw\.json\('decide'/g)?.length).toBe(1)
    const calls = desk.match(/.*this\.byModel\(.*/g) ?? []
    expect(calls.length).toBeGreaterThan(0)
    for (const line of calls) expect(line).toMatch(/if \(!this\.settings\.rules\)/)
    expect(desk).not.toMatch(/'answer'/)
  })

  test('settings in config: no model name, price or threshold in the desk code', () => {
    for (const [f, s] of sources('src/desk')) expect(s, f).not.toMatch(/sm-small|sm-large|gpt-|claude-|minLexical\s*[:=]\s*\d/)
  })

  test('the demo seed holds what the desk received and decided, not the truth', () => {
    const seed = readFileSync(join(ROOT, 'demo/seed.json'), 'utf8')
    expect(seed).not.toMatch(/"truth"|"traps"|"scenario"|"facts":\s*\[/)
  })

  test('generated reports: every headline number in the README comes from reports/dev.json', () => {
    const readme = readFileSync(join(ROOT, 'README.md'), 'utf8')
    const dev = JSON.parse(readFileSync(join(ROOT, 'reports/dev.json'), 'utf8'))
    const p = dev.designs.find((d: { name: string }) => d.name === 'platform').metrics
    expect(readme).toContain(`${(p.right * 100).toFixed(1)}%`)
    expect(readme).toContain('<!-- generated by npm run readme -->')
  })

  test('a small world end to end: the desk answers right, never twice in SAP; one model alone does not', async () => {
    const w = smallWorld('e2e', { tickets: 200, warranty: { ...smallWorld('x').cfg.warranty, followUpShare: 0.4, resentShare: 0.4 }, sap: { ghostTimeout: 0.3 } })
    const tickets = await w.tickets()
    const desk = await runDesign(w, tickets, { name: 'platform', label: '', kind: 'desk', rules: true, verifier: true }, cfg, data)
    const alone = await runDesign(w, tickets, { name: 'model_alone', label: '', kind: 'model_alone' }, cfg, data)
    expect(desk.duplicateRmas).toBe(0)
    expect(desk.tickets.filter((t) => t.right).length / tickets.length).toBeGreaterThan(0.97)
    expect(desk.tickets.filter((t) => t.injectionFollowed)).toHaveLength(0)
    expect(desk.tickets.filter((t) => t.handledBy === 'auto' && t.replyDefects.length)).toHaveLength(0)
    expect(alone.duplicateRmas).toBeGreaterThan(0)
    expect(alone.tickets.filter((t) => t.wrongSent).length).toBeGreaterThan(desk.tickets.filter((t) => t.wrongSent).length)
  })
})
